"""The pre-write path guard — one rule engine, every harness.

Rule 1 says records are written only via the maestro CLI. Three things enforce it,
at three different moments:

    write attempt ──► THIS MODULE (pre-write, refuses before the file changes)
    after a write ──► frontmatter stamp     (docs stamp --check)
    at a commit   ──► templates/pre-commit  (stamp + docs check --staged)

Only the first is harness-shaped, because only the first has to read a tool call.
Kept only in a hook, it would be a Claude Code feature: dsh had no pre-write guard, so a
hand-edit of an INDEX.md under dsh was caught by nothing (INDEX files carry no stamp),
and a hand-edit of a record's frontmatter was caught only afterwards. The rule lives here
so both harnesses can be thin adapters over it:

    Claude Code  global/hooks/guard_records.py  imports verdict() directly
    dsh          (plugin removed)

The GRANULARITY is the point (it is what the first version of the hook got wrong,
blocking records wholesale and so blocking the legitimate half too):

    frontmatter        CLI-owned    denied
    an epic's ## Log   CLI-owned    denied   (the CLI writes it via --note)
    INDEX.md           generated    denied outright
    record body prose  hand-edited  ALLOWED — that is where write-ups are authored
    findings/progress  hand-edited  ALLOWED — never guarded
    a new record file  CLI-scaffold denied (frontmatter + INDEX stay consistent)

How hard each of the three stops — deny, or warn and let the write through — is the
gate mode, `MAESTRO_GATES` (gates.py), read by the Claude Code adapters only; `verdict`
itself always answers the rule.

It does not police the CLI itself: the CLI writes records through its own file I/O
inside a shell subprocess, so it never arrives here as a write-tool call.
"""
