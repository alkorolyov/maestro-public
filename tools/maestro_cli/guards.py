# ── normalising the two tool dialects ────────────────────────────────────────
#
# Claude Code   Write{file_path, content} · Edit{file_path, old_string} · MultiEdit{edits[]}
# dsh           write{file_path, content} · edit{file_path, old_string}
#               str_replace_editor{path, command, file_text, old_str, new_str, insert_line}
#
# The KEYS decide the shape, not the tool name: a harness that renames its tools, or
# adds one, still lands in the right branch. `command: view` is the one name-shaped
# case, because a read and a create differ only by that word.

class Call:
    """A write-tool call reduced to what the rule needs."""

    __slots__ = ("path", "content", "olds", "read_only")

    def __init__(self, path: str, content: str | None, olds: list[str], read_only: bool):
        self.path = path
        self.content = content       # whole-file payload, or None for a string replace
        self.olds = olds             # literal strings this call will replace
        self.read_only = read_only


def normalize(tool: str, tool_input: dict) -> Call | None:
    """A tool call as (path, content, olds), or None when it writes no single file."""
    path = tool_input.get("file_path") or tool_input.get("path") or ""
    if not path or not isinstance(path, str):
        return None
    command = tool_input.get("command")
    if command in ("view", "undo_edit"):
        return Call(path, None, [], read_only=True)

    content = tool_input.get("content")
    if content is None:
        content = tool_input.get("file_text")

    olds: list[str] = []
    for edit in tool_input.get("edits") or [tool_input]:
        if not isinstance(edit, dict):
            continue
        old = edit.get("old_string") or edit.get("old_str")
        if old:
            olds.append(old)
    return Call(path, content if isinstance(content, str) else None, olds, read_only=False)


# ── the CLI-owned regions of a record ────────────────────────────────────────

def owned_spans(text: str, kind: str) -> list[tuple[int, int]]:
    """(start, end) offsets of every CLI-owned region, in order.

    The frontmatter block for every record kind, plus — for an epic — its `## Log`
    section: exactly the surface `frontmatter.stamp_of` hashes, so the pre-write guard
    and the post-write stamp agree on what "CLI-owned" means. A record with no
    frontmatter block is not in CLI shape and is not policed at all.
    """
    m = FM_RE.match(text)
    if not m:
        return []
    spans = [(0, m.end())]
    if kind == "epic":
        log = _LOG_RE.search(text, m.end())
        if log:
            tail = _NEXT_H2_RE.search(text, log.end())
            spans.append((log.end(), tail.start() if tail else len(text)))
    return spans


def _owned_text(text: str, kind: str) -> list[str]:
    return [text[a:b] for a, b in owned_spans(text, kind)]


def _record_verdict(kind: str, name: str, call: Call, current: str | None) -> str | None:
    help_text = _CLI_HELP[kind]
    if current is None:
        return (
            f"{name} does not exist — a new {kind} record is scaffolded by the CLI, "
            f"never hand-created (frontmatter + INDEX stay consistent that way):\n{help_text}"
        )
    spans = owned_spans(current, kind)
    if not spans:
        return None  # no frontmatter block → not CLI-owned shape; not ours to police

    owned = "FRONTMATTER" if kind != "epic" or len(spans) == 1 else "FRONTMATTER or the `## Log`"

    if call.content is not None:
        if _owned_text(call.content, kind) == _owned_text(current, kind):
            return None  # owned regions byte-identical → a body rewrite, allowed
        return (
            f"{name}: this write changes the {owned}, which is maestro-owned — "
            f"only the body prose is hand-edited. Keep it byte-identical, "
            f"or go through the CLI:\n{help_text}"
        )

    # A string replace is allowed only when every occurrence provably sits outside the
    # owned regions. A payload the guard cannot scope (no old_string at all — an insert,
    # or an unknown tool shape) fails CLOSED, as the original whole-file guard did.
    if not call.olds:
        return (
            f"{name} is a maestro-owned record — this call carries no literal old text the "
            f"guard can scope to the body, so it is denied. Body prose is hand-edited "
            f"via an edit tool; the {owned} goes through the CLI:\n{help_text}"
        )
    for old in call.olds:
        pos = current.find(old)
        while pos != -1:
            if any(pos < end and pos + len(old) > start for start, end in spans):
                return (
                    f"{name}: this edit touches the {owned}, which is maestro-owned — "
                    f"only the body prose is hand-edited. Use the CLI:\n{help_text}"
                )
            pos = current.find(old, pos + 1)
    return None


def verdict(tool: str, tool_input: dict, read=None) -> str | None:
    """The reason to DENY this tool call, or None to allow it.

    `read(path) -> str | None` reads the file as it is now (None when absent); the
    default reads the real filesystem. Injectable so the rule can be tested without
    a filesystem, and so an adapter can pass a sandboxed reader.
    """
    if read is None:
        def read(p):
            try:
                return Path(p).read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                return None

    call = normalize(tool, tool_input)
    if call is None or call.read_only:
        return None

    p = PurePosixPath(call.path)
    name, parts = p.name, p.parts

    # Dataset records (docs/data/<name>.md) are a hybrid: the CLI owns the provenance
    # frontmatter (sha/version/source), the description body is hand-edited, and they
    # carry no stamp. So block CREATION only — that is the step that must compute a
    # sha from data/raw/ rather than have one typed in. Scope strictly to a docs/ tree:
    # data/raw/ and data/experiments/ artifacts contain a 'data' part too.
    in_docs_data = len(parts) >= 2 and parts[-2] == "data" and "docs" in parts[:-1]
    if in_docs_data and name.endswith(".md") and name != "INDEX.md":
        if read(call.path) is None:
            return (
                f"{name} looks like a new dataset record under docs/data/ — don't hand-create it. "
                "Use the CLI so the sha256 is computed from data/raw/ (never hand-typed):\n"
                + _CLI_HELP["dataset"]
            )
        return None

    if name == "INDEX.md" and (
        (len(parts) >= 2 and parts[-2] in _INDEX_DIRS)
        or parts[-3:] == ("kb", "literature", "INDEX.md")
    ):
        return _INDEX_REASON

    for kind, directory, pattern in _RECORDS:
        if directory in parts and pattern.match(name):
            current = read(call.path)
            reason = _record_verdict(kind, name, call, current)
            if reason and current is not None and _resolves_a_merge(call, tool_input, current, kind):
                return None
            return reason
    return None


def _result_text(call: Call, tool_input: dict, current: str) -> str | None:
    """The file as this call would leave it, or None when the call cannot be replayed."""
    if call.content is not None:
        return call.content
    text = current
    for edit in tool_input.get("edits") or [tool_input]:
        if not isinstance(edit, dict):
            return None
        old = edit.get("old_string") or edit.get("old_str")
        new = edit.get("new_string", edit.get("new_str"))
        if not old or not isinstance(new, str) or old not in text:
            return None
        text = text.replace(old, new) if edit.get("replace_all") else text.replace(old, new, 1)
    return text


def _resolves_a_merge(call: Call, tool_input: dict, current: str, kind: str) -> bool:
    """During a merge, a write that leaves the CLI-owned surface equal to one side's is
    conflict resolution, not a hand edit (tools/maestro_cli/gitstate.py)."""
    from . import gitstate
    path = Path(call.path)
    if not path.is_absolute() or not gitstate.merge_heads(path.parent):
        return False
    result = _result_text(call, tool_input, current)
    if result is None:
        return False
    return gitstate.taken_from_a_side(path, result, lambda t: _owned_text(t, kind))


# ── the live-child rule ──────────────────────────────────────────────────────
#
# The second guard both harnesses now run, and the one that started on the dsh side.
# A parent agent and its background children share ONE git checkout. A child's report
# is PROGRESS, not completion: the parent can receive it while the child keeps editing
# files for another half hour. A parent once read a report as "done", ran `git switch
# main && git merge --no-ff feat/x && git branch -d feat/x`, and the child's later edits
# landed uncommitted on main.
#
# So while a child of this agent is still running, a shell command that moves the branch
# under it is denied. The offence is the command TEXT, which is why both harnesses put
# this on the pre-execute/PreToolUse side. Reads pass.
#
# The patterns are declared HERE and mirrored in the removed dsh plugin, which
# cannot import Python at load time. test_guards.py asserts the two lists are identical,
# so the mirror cannot drift in silence.

LIVE_CHILD_PATTERNS = (
    # Word-boundary safe: `git log --merges` and `git branch --show-current` must not
    # match, `git branch -D feat/x` must. `merge` also excludes the hyphenated read-only
    # verbs — `git merge-base`, `git merge-tree` — which a bare \b let through.
    r"\bgit\s+merge\b(?!-)",
    r"\bgit\s+switch\b",
    r"\bgit\s+checkout\b",
    r"\bgit\s+branch\b[^;&|\n]*(?:\s|^)(?:-d|-D|--delete)\b",
    r"\bgit\s+reset\b",
    r"\bgit\s+rebase\b",
    r"\bgit\s+stash\b",
)

_LIVE_CHILD = tuple(re.compile(p) for p in LIVE_CHILD_PATTERNS)


# ── the blocked-command echo, shared by both command guards ──────────────────
#
# A refusal ends by quoting the command that fired it, and that quote used to be
# `command[:200] + "…"`. A head truncation hides the offence whenever the offending verb
# sits at the TAIL of a long command, which is the common shape: a long
# `maestro epic item … --note="<prose>" && git checkout main -q` was denied
# and the echo showed only the note's prose — the `git checkout` that actually fired the
# guard was invisible, and the model recovered by guessing what it had done wrong.
#
# So the echo is cut around the MATCH instead, and names the text that matched. Mirrored
# in both .mjs guards (`blockedExcerpt`), which cannot import this; the dsh tests pin each
# mirror to the builder here by string equality, so the copies cannot drift.

ECHO_WIDTH = 200   # characters of command text the echo may show
ECHO_LEAD = 60     # how many of them come BEFORE the match, so the match keeps its context
ECHO_MATCH = 40    # cap on the quoted matched text itself


def blocked_excerpt(command: str, patterns) -> str:
    """`Blocked command …` — the last sentence of both refusals, cut around the offence.

    A command that fits in ECHO_WIDTH is quoted whole, as before. A longer one is cut to
    a window around the EARLIEST match, `…` marking each cut end, and the matched text is
    named with its offset so the model can see which verb it is being refused for rather
    than guess. A long command that matched nothing (a caller quoting something else)
    falls back to the old head truncation.
    """
    if not isinstance(command, str):
        command = str(command)
    earliest = None
    for pattern in patterns:
        m = pattern.search(command)
        if m and (earliest is None or m.start() < earliest.start()):
            earliest = m
    if len(command) <= ECHO_WIDTH:
        return f"Blocked command: {command}"
    if earliest is None:
        return f"Blocked command: {command[:ECHO_WIDTH]}…"
    matched = earliest.group(0)
    if len(matched) > ECHO_MATCH:
        matched = matched[:ECHO_MATCH] + "…"
    lead_start = max(0, earliest.start() - ECHO_LEAD)
    lead = command[lead_start:earliest.start()]
    rest = command[earliest.start():earliest.start() + (ECHO_WIDTH - len(lead))]
    head = "…" if lead_start > 0 else ""
    tail = "…" if earliest.start() + len(rest) < len(command) else ""
    return (f"Blocked command ({len(command)} chars, `{matched}` at char "
            f"{earliest.start()}): {head}{lead}{rest}{tail}")


def moves_the_branch(command: str) -> bool:
    """True when this shell command would move the checkout under a running child."""
    return isinstance(command, str) and any(p.search(command) for p in _LIVE_CHILD)


def live_child_reason(command: str, children) -> str:
    """The deny reason, worded the same in both harnesses.

    `children` are the ids of this agent's children still running — named, because
    "a child is running" sends the model looking and "child 6d4e7232 is running" does
    not.
    """
    return (
        f"A background child agent is still running ({', '.join(children)}), in this same "
        "checkout. A child's report is PROGRESS, not completion — it keeps editing files "
        "after it reports, and its later edits would land on whatever branch you switch to. "
        "Wait for the child's \"finished\" event (the one that says it will do no further "
        "work) before merging, switching or creating branches, deleting a branch, "
        "resetting, rebasing or stashing. Waiting means ENDING YOUR STEP: you are woken by "
        "the \"Background subagent … finished\" message, which opens a new turn — never poll "
        "with `sleep` (the shell kills a long one and prints nothing), and a subagent id is "
        "not a job id. Until then: steer it with send_message, or stop it with "
        "interrupt_agent. "
        + blocked_excerpt(command, _LIVE_CHILD)
    )


# ── the executor rule ────────────────────────────────────────────────────────
#
# The mirror image of the live-child rule, seen from the CHILD. A delegated executor
# shares its parent's checkout, and that tree may hold the parent's uncommitted
# knowledge-base writes: the orchestrator writes the epic board through the CLI and
# commits it at merge time, so between spawn and merge those edits exist only in the
# working tree. Executors have wiped them this way: a `git stash`, a `git checkout main -- .`
# and a `git stash drop` on the parent's stash, among others. Briefs forbade all of it in
# capitals, and some executors did it anyway.
# A rule the model must remember is not a rule — this one is enforced before the
# command runs.
#
# Inside a delegated session, a shell command that discards uncommitted work, moves the
# shared tree or publishes is denied: stash, reset, clean, restore, worktree, a
# checkout with a pathspec (`git checkout [<ref>] -- <path>` reverts files), merge,
# rebase, push, branch delete. Cutting a branch (`git checkout -b`, `git switch -c`),
# committing explicit paths, and every read pass. Nothing is blocked in a top-level
# session — the parent's own merges are the live-child rule's business, not this one's.
#
# Declared HERE and mirrored in the removed dsh plugin; test_guard_executor.py
# pins the two lists to each other.

EXECUTOR_PATTERNS = (
    r"\bgit\s+stash\b",
    r"\bgit\s+reset\b",
    r"\bgit\s+clean\b",
    r"\bgit\s+restore\b",
    r"\bgit\s+worktree\b",
    # `git checkout [<ref>] -- <path>`: the pathspec form overwrites files in the tree.
    # `git checkout -b feat/x` and `git checkout main` carry no ` -- ` and pass.
    r"\bgit\s+checkout\b[^;&|\n]*\s--\s",
    r"\bgit\s+merge\b(?!-)",
    r"\bgit\s+rebase\b",
    r"\bgit\s+push\b",
    r"\bgit\s+branch\b[^;&|\n]*(?:\s|^)(?:-d|-D|--delete)\b",
)

_EXECUTOR = tuple(re.compile(p) for p in EXECUTOR_PATTERNS)


def discards_shared_work(command: str) -> bool:
    """True when this shell command, run by a delegated child, would discard uncommitted
    work in the shared tree, move it, or publish it."""
    return isinstance(command, str) and any(p.search(command) for p in _EXECUTOR)


def executor_reason(command: str) -> str:
    """The deny reason, worded the same in both harnesses."""
    return (
        "This session is a delegated child that shares its parent's checkout. The working "
        "tree may hold the parent's UNCOMMITTED knowledge-base writes (docs/, the epic board), "
        "and this command discards or moves uncommitted work — an executor's `git stash` "
        "and another's `git checkout main -- .` wiped the "
        "orchestrator's board writes. From a child: never stash, reset, clean, restore, add a "
        "worktree, check out paths, merge, rebase, push, or delete a branch. To undo your own "
        "edit, edit the file back. A baseline measured on main belongs in your brief — if it is "
        "missing, report that instead of visiting main. "
        + blocked_excerpt(command, _EXECUTOR)
    )


# ── the root-writes-code rule ────────────────────────────────────────────────
#
# Core rule 9 splits the lanes: the orchestrator plans, writes docs/ and merges; an
# executor writes the code. Nothing enforced it, and without a guard the split does not
# hold: one dsh planner (the ROOT agent, delegationDepth 0) held a single large item,
# spawned children and wrote code itself. Both lanes in one agent means the merge is
# reviewed by the author of the code, and the orchestrator's context is spent on the work
# it is supposed to be steering.
#
# THE RULE: in a TOP-LEVEL session (depth 0), a write to a TRACKED path outside docs/ is
# denied — through a write/edit tool, or through a shell command that writes files.
#
# The exemptions are the orchestrator's own surface: docs/ (its records, board and
# findings), the instruction files it maintains (CLAUDE.md, README.md, AGENTS.md) and
# .claude/. An UNTRACKED path passes too, which is the deliberate hole in this guard: git
# is what says "this is the project's code", and a brand-new file is the one case it
# cannot say it about. A guard that fired on every scratch file, log and build artifact
# in the tree would be turned off within a day.
#
# Scoped to maestro projects (a docs/ tree with records), like the spawn rule: this is a
# maestro rule, and a guard installed machine-wide must not take over every checkout on
# the machine. The opt-out is `[agents.dsh] root_writes_code = true` in maestro.toml — the
# human-owned file (policy.py), for the "small item, the planner codes it itself in a
# short session" mode. maestro.toml is itself a tracked non-docs path, so the agent
# cannot grant itself the opt-out without the refusal it is trying to get past.
#
# Declared HERE and mirrored in the removed dsh plugin; test_guard_root_code.py
# pins the two lists to each other.

ROOT_CODE_WRITE_PATTERNS = (
    # In-place and copy-shaped writes. Each one is only half the test: a command matches
    # here, and then has to name a tracked non-docs path before anything is denied.
    r"\bsed\b[^;&|\n]*\s(?:-i|--in-place)",
    r"\btee\b",
    r"\b(?:cp|mv)\s",
    r"(?:^|[\s;&|])patch\s",
    r"\bgit\s+apply\b",
    # An inline python that opens a file for writing, or writes a Path. `[\s\S]` rather
    # than `.` because the script arrives as a heredoc, spanning newlines.
    r"""\bpython3?\b[\s\S]*\bopen\([^)]*['"][wax]""",
    r"\bpython3?\b[\s\S]*\.write_text\(",
    # LAST, and treated specially: a shell redirect (`cat > f`, `echo >> f`). Only its
    # own TARGET is considered a written path — every other pattern lets the whole
    # command be scanned. Without that split, `grep -rn x rust/*.rs > /tmp/hits` would be
    # refused for the files it READ, which is how a guard earns its way into a --no-verify.
    r">>?\s*[^\s;&|<>]",
)

# Presets whose session IS the executor (one agent, no subagents) although it runs at depth 0.
# Matches the name or `<name>-...` (the launcher derives `<name>-ctx<K>k`). Mirrored in the
# .mjs; test_guard_root_code.py pins the two lists to each other.
EXECUTOR_PRESETS = ("item-solo",)

# The environment variable the dsh launcher (dsh-tui-local) sets to the session's preset.
PRESET_ENV = "DSH_TUI_PRESET"

_ROOT_CODE = tuple(re.compile(p) for p in ROOT_CODE_WRITE_PATTERNS)
_ROOT_CODE_IN_PLACE = _ROOT_CODE[:-1]

_REDIRECT_TARGET_RE = re.compile(r">>?\s*([^\s;&|<>]+)")

# Everything that cannot appear inside a shell path token. Splitting on it pulls a path
# out of `open('rust/x.rs','w')` and out of `--file=rust/x.rs` alike.
_PATH_SPLIT_RE = re.compile(r"[\s'\"()<>|&;,`=]+")

# The orchestrator's own files, wherever they sit in the tree.
ECHO_PATHS = 5   # written paths the refusal names before it says "(+N more)"

INSTRUCTION_FILES = frozenset({"CLAUDE.md", "README.md", "AGENTS.md"})
